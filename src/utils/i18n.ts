const REPLACEMENTS: Array<[string, string]> = Object.entries(EN_TRANSLATIONS)
  .sort((a, b) => b[0].length - a[0].length);

export const getLanguage = (): GameLanguage => {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return saved === 'ru' ? 'ru' : 'en';
  } catch {
    return 'en';
  }
};

export const setLanguage = (language: GameLanguage): void => {
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // If storage is blocked, the reload will still use the English default.
  }
  document.documentElement.lang = language;
  window.location.reload();
};

export const translateText = (input: string, language: GameLanguage = getLanguage()): string => {
  if (language === 'ru' || !/[А-Яа-яЁё]/.test(input)) return input;

  const leading = input.match(/^\s*/)?.[0] ?? '';
  const trailing = input.match(/\s*$/)?.[0] ?? '';
  const core = input.trim();

  const exact = EN_TRANSLATIONS[core];
  if (exact) return `${leading}${exact}${trailing}`;

  for (const [pattern, replacer] of DYNAMIC_TRANSLATORS) {
    const match = core.match(pattern);
    if (match) {
      return `${leading}${replacer(...match)}${trailing}`;
    }
  }

  let translated = core;
  for (const [ru, en] of REPLACEMENTS) {
    if (translated.includes(ru)) translated = translated.split(ru).join(en);
  }

  // Small grammatical/measurement fallbacks for dynamic strings.
  translated = translated
    .replace(/\bминуты\b/g, 'minutes')
    .replace(/\bминут\b/g, 'minutes')
    .replace(/\bмин\b/g, 'min')
    .replace(/\bсекунд\b/g, 'seconds')
    .replace(/\bсек\b/g, 'sec')
    .replace(/\bместа\b/g, 'slots')
    .replace(/\bмест\b/g, 'slots')
    .replace(/\bмонеты\b/g, 'coins')
    .replace(/\bмонет\b/g, 'coins');

  return `${leading}${translated}${trailing}`;
};

const translateElement = (element: Element): void => {
  for (const attribute of ['title', 'aria-label', 'placeholder']) {
    const value = element.getAttribute(attribute);
    if (value && /[А-Яа-яЁё]/.test(value)) {
      element.setAttribute(attribute, translateText(value, 'en'));
    }
  }
};

const translateNode = (node: Node): void => {
  if (node.nodeType === Node.TEXT_NODE) {
    const value = node.nodeValue;
    if (value && /[А-Яа-яЁё]/.test(value)) {
      node.nodeValue = translateText(value, 'en');
    }
    return;
  }

  if (!(node instanceof Element)) return;
  translateElement(node);

  const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let current = walker.nextNode();
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) {
      const value = current.nodeValue;
      if (value && /[А-Яа-яЁё]/.test(value)) current.nodeValue = translateText(value, 'en');
    } else if (current instanceof Element) {
      translateElement(current);
    }
    current = walker.nextNode();
  }
};

export const startDomLocalization = (): (() => void) => {
  const language = getLanguage();
  document.documentElement.lang = language;

  if (language === 'ru') return () => {};

  translateNode(document.body);

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        translateNode(mutation.target);
      } else if (mutation.type === 'attributes' && mutation.target instanceof Element) {
        translateElement(mutation.target);
      } else {
        mutation.addedNodes.forEach(translateNode);
      }
    }
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['title', 'aria-label', 'placeholder'],
  });

  return () => observer.disconnect();
};
